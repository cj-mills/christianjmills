// The American English check (hub decision 2026-11-09-american-english-written-from-the-start):
// reader-facing text is written in American English, with dates in American order. This finds
// British spellings and day-before-month dates and says where; it never rewrites anything. The
// publish command refuses a bundle that has any, and the site's build checks the site's own text.
//
// Which spellings are British comes from VarCon (spec/english/varcon.txt): a word is refused when
// VarCon tags it British (B, or Bv, a common British variant) and nowhere tags it American (A, or
// Av, a common American variant). So a word both dialects use passes, and so does a word that is
// British in one sense and American in another. Each refusal names VarCon's American spelling.
import { readFileSync } from 'node:fs';
import Markdoc, { type Node } from '@markdoc/markdoc';
import type { Manifest } from './manifest.ts';

export interface Finding {
  line: number;
  found: string;
  message: string;
}

let table: Map<string, string> | undefined;

/** British spellings and the American spelling of each, from VarCon. */
export function britishSpellings(): Map<string, string> {
  if (table) return table;
  const american = new Set<string>();
  const british: [word: string, american: string][] = [];
  // VarCon's entries come in clusters under a "# word <verified> (level n)" line. Its unverified
  // clusters are generated by rule, and the rules for -re and for ae and oe pair real words with
  // each other ("acre" with "acer"), so from those only the -ise and -yse spellings are taken.
  let verified = false;
  for (const raw of readFileSync(new URL('./english/varcon.txt', import.meta.url), 'utf8').split('\n')) {
    if (raw.startsWith('#')) verified = raw.includes('<verified>');
    if (!raw || raw.startsWith('#')) continue;
    const entries = raw
      .split(' | ')[0]
      .split(' / ')
      .map((e) => {
        const at = e.indexOf(': ');
        return { tags: e.slice(0, at).split(' '), word: e.slice(at + 2).trim().toLowerCase() };
      })
      .filter((e) => /^[a-z]+$/.test(e.word));
    const has = (tags: string[], letter: string) => tags.some((t) => t === letter || t === letter + '.' || t === letter + 'v');
    const primary = entries.find((e) => e.tags.includes('A') || e.tags.includes('A.'))?.word;
    for (const e of entries) {
      if (has(e.tags, 'A')) american.add(e.word);
      if (!has(e.tags, 'B') || !primary || primary === e.word) continue;
      if (verified || e.word.replaceAll('s', 'z') === primary.replaceAll('s', 'z')) british.push([e.word, primary]);
    }
  }
  table = new Map(british.filter(([w]) => !american.has(w)));
  return table;
}

const MONTHS = 'January|February|March|April|May|June|July|August|September|October|November|December';
const DAY_FIRST = new RegExp(`\\b(\\d{1,2})(?:st|nd|rd|th)?\\s+(${MONTHS})\\b`, 'g');

/** Blanks out each allowed name or quotation, so what is inside it isn't read. */
function mask(text: string, allow: string[]): string {
  let out = text;
  for (const phrase of allow) if (phrase) out = out.split(phrase).join(' '.repeat(phrase.length));
  return out;
}

/** The British spellings and day-first dates in a text, by line (1-based, plus `firstLine` - 1). */
export function checkText(text: string, allow: string[] = [], firstLine = 1): Finding[] {
  const words = britishSpellings();
  const out: Finding[] = [];
  mask(text, allow)
    .split('\n')
    .forEach((line, i) => {
      // camelCase and snake_case names are read word by word.
      for (const m of line.replace(/([a-z])([A-Z])/g, '$1 $2').matchAll(/[A-Za-z]+/g)) {
        const american = words.get(m[0].toLowerCase());
        if (american) out.push({ line: firstLine + i, found: m[0], message: `"${m[0]}" is a British spelling; the American is "${american}"` });
      }
      for (const m of line.matchAll(DAY_FIRST))
        out.push({ line: firstLine + i, found: m[0], message: `"${m[0]}" puts the day before the month; write "${m[2]} ${m[1]}"` });
    });
  return out;
}

/** Tag attributes whose value is text the reader sees. */
const PROSE_ATTRIBUTES = ['caption', 'alt', 'title', 'label', 'kind', 'note'];
const TEXT_ASSETS = /\.(m?js|json|txt|md|csv|svg|css|html)$/;

function checkMarkdoc(source: string, allow: string[]): Finding[] {
  const out: Finding[] = [];
  const walk = (node: Node, quoted: boolean) => {
    const line = (node.lines?.[0] ?? 0) + 1;
    // Code is quoted from its file and a block quote from its source: both stay as written.
    if (node.type === 'fence' || node.type === 'code' || node.type === 'blockquote') return;
    if (node.type === 'text' && !quoted) out.push(...checkText(String(node.attributes.content ?? ''), allow, line));
    if (node.type === 'tag')
      for (const name of PROSE_ATTRIBUTES)
        if (typeof node.attributes[name] === 'string') out.push(...checkText(node.attributes[name], allow, line));
    for (const child of node.children) walk(child, quoted);
  };
  walk(Markdoc.parse(source), false);
  return out;
}

/** Every British spelling and day-first date in what a bundle shows its readers: the manifest's
 *  wording, the page's text (not its code or block quotes) and the bundle's text files. Returns
 *  one line per finding, with its file and line; the manifest's `english.allow` lists the names and
 *  quotations that keep their own spelling. */
export function checkBundle(files: Map<string, Uint8Array>, manifest: Manifest): string[] {
  const allow = manifest.english?.allow ?? [];
  const decode = (name: string) => new TextDecoder().decode(files.get(name)!);
  const problems: string[] = [];
  const report = (file: string, findings: Finding[], where = (f: Finding) => `${file}:${f.line}`) => {
    for (const f of findings.slice(0, 20)) problems.push(`${where(f)}: ${f.message}`);
    if (findings.length > 20) problems.push(`${file}: and ${findings.length - 20} more`);
  };

  // A source's citation is a title, so it stays as written.
  const wording: [field: string, text: string][] = [
    ['title', manifest.title],
    ['summary', manifest.summary],
    ...manifest.revisions.map((r, i): [string, string] => [`revisions[${i}].note`, r.note]),
    ...manifest.interactives.map((x, i): [string, string] => [`interactives[${i}].description`, x.description]),
    ...manifest.sources.flatMap((s, i): [string, string][] => [[`sources[${i}].label`, s.label], [`sources[${i}].rights`, s.rights]]),
  ];
  for (const [field, text] of wording) report('manifest.json', checkText(text, allow), () => `manifest.json: ${field}`);

  for (const name of [...files.keys()].sort()) {
    if (name.startsWith('content/') && name.endsWith('.mdoc')) report(name, checkMarkdoc(decode(name), allow));
    else if (name.startsWith('assets/') && TEXT_ASSETS.test(name)) report(name, checkText(decode(name), allow));
  }
  return problems;
}
